"""Exports a Markdown report as a PDF (reportlab) or as LaTeX tables (booktabs)."""

import re


def _inline(text: str) -> str:
    """Markdown bold and code spans as the markup reportlab understands."""

    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)

    return re.sub(r"`(.+?)`", r"<font face='Courier'>\1</font>", text)


def _cells(line: str) -> list[str] | None:
    """The cells of a Markdown table row; None for the |---|---| separator."""

    cells = line.strip().strip("|").split("|")

    return None if all(re.fullmatch(r"\s*:?-+:?\s*", c) for c in cells) else [c.strip() for c in cells]


def write_pdf(markdown: str, path: str) -> str:
    """The report as a PDF (landscape A4): headings, tables, bullets and paragraphs."""

    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import cm
    from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    base = getSampleStyleSheet()["Normal"]
    body = ParagraphStyle("body", parent=base, fontSize=9.5, leading=13, spaceAfter=5)
    cell = ParagraphStyle("cell", parent=body, fontSize=8, leading=10, spaceAfter=0)
    head = ParagraphStyle("head", parent=cell, fontName="Helvetica-Bold", textColor=colors.white)
    styles = {"# ": ParagraphStyle("h0", parent=body, fontName="Helvetica-Bold", fontSize=18, leading=22, spaceAfter=8),
              "## ": ParagraphStyle("h1", parent=body, fontName="Helvetica-Bold", fontSize=13, leading=16, spaceBefore=10),
              "### ": ParagraphStyle("h2", parent=body, fontName="Helvetica-Bold", fontSize=10.5, leading=13, spaceBefore=6)}
    story, rows = [], []

    def flush():
        if not rows:
            return
        data = [[Paragraph(_inline(c), head if r == 0 else cell) for c in row] for r, row in enumerate(rows)]
        table = Table(data, repeatRows=1, colWidths=[(A4[1] - 3 * cm) / len(rows[0])] * len(rows[0]))
        table.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1f3a5f")),
                                   ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#b8c2d0")), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                                   *[("BACKGROUND", (0, r), (-1, r), colors.HexColor("#f1f4f8")) for r in range(2, len(rows), 2)]]))
        story.extend([table, Spacer(1, 6)])
        rows.clear()

    for line in markdown.split("\n"):

        if line.startswith("|"):
            cells = _cells(line)
            if cells is not None:
                rows.append(cells)
            continue

        flush()

        if line.strip() == "---":
            story.append(PageBreak())
        elif line.startswith(("### ", "## ", "# ")):
            prefix = next(p for p in ("### ", "## ", "# ") if line.startswith(p))
            story.append(Paragraph(_inline(line[len(prefix):]), styles[prefix]))
        elif line.startswith("- "):
            story.append(Paragraph(_inline(line[2:]), body, bulletText="\u2022"))
        elif line.startswith("> "):
            story.append(Paragraph(_inline(line[2:]), body))
        elif line.strip():
            story.append(Paragraph(_inline(line), body))

    flush()
    SimpleDocTemplate(path, pagesize=landscape(A4), leftMargin=1.5 * cm, rightMargin=1.5 * cm, topMargin=1.5 * cm,
                      bottomMargin=1.5 * cm, title="Document-QA architecture comparison").build(story)

    return path


_NUMERIC = re.compile(r"^[\s*\-+\d.,/%()~<>=a-z]*\d[\s*\d.,/%()a-z\-+~]*$", re.I)


def _latex_text(text: str) -> str:
    """Plain text made safe for LaTeX; **bold** becomes \\textbf."""

    text = text.replace("`", "")

    for char in "&%_#$":
        text = text.replace(char, "\\" + char)

    text = text.replace("~", "\\textasciitilde{}")

    return re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", text)


def to_latex(markdown: str) -> str:
    """Every Markdown table as a booktabs table: scaled to the line width (no overflow),
    one caption per table built from its section titles (so captions stay unique across
    reports), a \\label each, and numeric columns right-aligned."""

    out = ["% Generated by benchmarks.docqa.report. Needs \\usepackage{booktabs} and \\usepackage{graphicx}.", ""]
    heads = {1: "", 2: "", 3: ""}
    table, count = [], 0

    def flush():
        nonlocal count
        if not table:
            return
        count += 1
        title = " -- ".join(part for part in (heads[1], heads[2], heads[3]) if part)
        label = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:60]
        width = len(table[0])
        numeric = [sum(bool(_NUMERIC.match(row[i])) for row in table[1:]) > 0.6 * max(1, len(table) - 1) for i in range(width)]
        align = "".join("r" if numeric[i] and i else "l" for i in range(width))
        out.extend(["\\begin{table}[t]", "\\centering", "\\small", f"\\caption{{{_latex_text(title)}}}\\label{{tab:{label}-{count}}}",
                    "\\resizebox{\\linewidth}{!}{%", f"\\begin{{tabular}}{{{align}}}", "\\toprule",
                    " & ".join(_latex_text(c) for c in table[0]) + " \\\\", "\\midrule"]
                   + [" & ".join(_latex_text(c) for c in row) + " \\\\" for row in table[1:]]
                   + ["\\bottomrule", "\\end{tabular}}", "\\end{table}", ""])
        table.clear()

    for line in markdown.split("\n"):

        if line.startswith("|"):
            cells = _cells(line)
            if cells is not None:
                table.append(cells)
            continue

        flush()

        if line.startswith("#"):
            level = len(line) - len(line.lstrip("#"))
            heads[min(level, 3)] = line.lstrip("# ").replace("`", "")
            for deeper in range(level + 1, 4):
                heads[deeper] = ""

    flush()

    return "\n".join(out)
